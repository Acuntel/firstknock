import { eventPlace, eventTitle, typeLabel, whyLine } from "../format";
import type { PropertyEvent } from "../types";
import type { ServiceArea } from "../scoring/types";

export interface RouteStop {
  order: number;
  score: number;
  title: string;
  place: string;
  why: string;
  /** Door and phone script for this specific property. */
  script: string;
  /** Miles from the previous stop, when both have coordinates. */
  legMiles: number | null;
}

export interface RouteLead {
  score: number;
  event: PropertyEvent;
}

const EARTH_RADIUS_MILES = 3958.7613;

function milesBetween(
  a: { lat: number; lng: number },
  b: { lat: number; lng: number },
): number {
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_RADIUS_MILES * Math.asin(Math.min(1, Math.sqrt(h)));
}

function coordsOf(lead: RouteLead): { lat: number; lng: number } | null {
  const { lat, lng } = lead.event.property;
  return typeof lat === "number" && typeof lng === "number" ? { lat, lng } : null;
}

/**
 * The script an operator reads at the door or on the phone.
 *
 * Deliberately not generated by a model. It is the same four beats every time,
 * the only variable is the record, and a person reading it aloud needs it to be
 * the same shape each morning rather than freshly worded. That also keeps door
 * knocking off the AI budget entirely.
 */
export function doorScript(lead: RouteLead, tenantName: string, now: Date): string {
  const event = lead.event;
  return [
    `Hi, I am with ${tenantName}.`,
    `I saw the ${typeLabel(event.type)} filed for this address, ${whyLine(event, now)}.`,
    "I am not here to sell you anything today. I wanted to introduce myself and leave a card in case it turns out to be useful.",
    "Is now a bad time?",
  ].join(" ");
}

/**
 * Orders today's leads into a drive route.
 *
 * Nearest neighbour from the tenant's service area centre. Not optimal, and it
 * does not try to be: the real constraint is that an operator drives it in the
 * morning, and a simple route they can follow beats a shorter one they cannot.
 *
 * Leads without coordinates keep their score order and are appended at the end,
 * which is the honest handling for Cook County today, where neither the sales
 * nor the permits feed publishes latitude and longitude.
 */
export function buildRouteSheet(
  leads: RouteLead[],
  tenantName: string,
  serviceArea: ServiceArea,
  now: Date,
  limit = 10,
): RouteStop[] {
  const top = [...leads].sort((a, b) => b.score - a.score).slice(0, limit);

  const located = top.filter((lead) => coordsOf(lead) !== null);
  const unlocated = top.filter((lead) => coordsOf(lead) === null);

  const ordered: Array<{ lead: RouteLead; legMiles: number | null }> = [];
  const remaining = [...located];
  let from = { lat: serviceArea.lat, lng: serviceArea.lng };

  while (remaining.length > 0) {
    let bestIndex = 0;
    let bestDistance = Number.POSITIVE_INFINITY;

    for (let i = 0; i < remaining.length; i += 1) {
      const distance = milesBetween(from, coordsOf(remaining[i] as RouteLead)!);
      if (distance < bestDistance) {
        bestDistance = distance;
        bestIndex = i;
      }
    }

    const [next] = remaining.splice(bestIndex, 1);
    ordered.push({ lead: next as RouteLead, legMiles: Math.round(bestDistance * 10) / 10 });
    from = coordsOf(next as RouteLead)!;
  }

  for (const lead of unlocated) ordered.push({ lead, legMiles: null });

  return ordered.map((entry, index) => ({
    order: index + 1,
    score: entry.lead.score,
    title: eventTitle(entry.lead.event),
    place: eventPlace(entry.lead.event),
    why: whyLine(entry.lead.event, now),
    script: doorScript(entry.lead, tenantName, now),
    legMiles: entry.legMiles,
  }));
}
